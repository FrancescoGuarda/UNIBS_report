--[[
unibs-common.lua -- helpers shared by report.lua and compendium.lua.

Turns DATA.yaml metadata and report front matter into the LaTeX calls defined
in headers/unibs-covers.tex, and applies body styling hooks (code boxes,
table header cells). Loaded with dofile() by the two filters.
]]

local path = pandoc.path
local utils = pandoc.utils

local M = {}

-- Project root = parent of the directory holding this file (headers/).
local here = path.directory(PANDOC_SCRIPT_FILE)
if path.is_relative(here) then
  here = path.join { pandoc.system.get_working_directory(), here }
end
M.root = path.directory(path.normalize(here))

--- Path as LaTeX expects it (forward slashes, also on Windows).
function M.texpath(p)
  return (p:gsub('\\', '/'))
end

M.MONTHS = {
  'gennaio', 'febbraio', 'marzo', 'aprile', 'maggio', 'giugno',
  'luglio', 'agosto', 'settembre', 'ottobre', 'novembre', 'dicembre',
}

-- Pattern of weekly report file names: YY-MM-DD.md
M.REPORT_PATTERN = '^(%d%d)%-(%d%d)%-(%d%d)%.md$'

local function warn(msg)
  io.stderr:write('[unibs] ' .. msg .. '\n')
end
M.warn = warn

--- Navigate nested metadata: M.get(meta, 'student', 'name').
function M.get(meta, ...)
  local v = meta
  for _, k in ipairs { ... } do
    if type(v) ~= 'table' and type(v) ~= 'userdata' then return nil end
    v = v[k]
    if v == nil then return nil end
  end
  return v
end

--- Plain-text value of a metadata field ('' when missing).
function M.str(v)
  if v == nil then return '' end
  return utils.stringify(v)
end

local function inlines_to_latex(inlines)
  local out = pandoc.write(pandoc.Pandoc { pandoc.Plain(inlines) }, 'latex')
  return (out:gsub('%s+$', ''))
end

--- LaTeX rendering of a metadata value (Markdown inline formatting kept).
function M.latex(v)
  if v == nil then return '' end
  local t = utils.type(v)
  if t == 'Inlines' then
    return inlines_to_latex(v)
  elseif t == 'Blocks' then
    return inlines_to_latex(utils.blocks_to_inlines(v))
  elseif t == 'Inline' then
    return inlines_to_latex(pandoc.Inlines { v })
  else
    return inlines_to_latex(pandoc.Inlines(utils.stringify(v)))
  end
end

--- ISO date (YYYY-MM-DD) -> "20 novembre 2026"; anything else unchanged.
function M.date_it(v)
  local s = M.str(v)
  local y, m, d = s:match('^(%d%d%d%d)%-(%d%d)%-(%d%d)')
  if y and M.MONTHS[tonumber(m)] then
    return string.format('%d %s %s', tonumber(d), M.MONTHS[tonumber(m)], y)
  end
  return s
end

--- Title size class (1-4) from its length: thresholds = max characters of
--- classes 1-3. The point size of each class is set in unibs-covers.tex.
function M.title_class(title, thresholds)
  local n = utf8.len(M.str(title)) or #M.str(title)
  for i, max in ipairs(thresholds) do
    if n <= max then return i end
  end
  return #thresholds + 1
end

local function exists(p)
  local fh = io.open(p, 'rb')
  if fh then fh:close() return true end
  return false
end

-- Placeholders ---------------------------------------------------------------

local SKIP = { ['header-includes'] = true, lang = true }

local function collect_placeholders(v, key, acc)
  local t = utils.type(v)
  if t == 'List' then
    for i, item in ipairs(v) do
      collect_placeholders(item, key .. '[' .. i .. ']', acc)
    end
  elseif t == 'table' or t == 'Meta' then
    for k, item in pairs(v) do
      if not SKIP[k] then
        collect_placeholders(item, key == '' and k or (key .. '.' .. k), acc)
      end
    end
  elseif t == 'Inlines' or t == 'Blocks' or t == 'string' then
    if utils.stringify(v):find('«', 1, true) then acc:insert(key) end
  end
end

--- Warn (stderr) about values still containing a «placeholder».
function M.warn_placeholders(meta, source)
  local acc = pandoc.List()
  collect_placeholders(meta, '', acc)
  if #acc > 0 then
    table.sort(acc)
    warn(string.format('%s: campi ancora da compilare (placeholder «…»): %s',
      source, table.concat(acc, ', ')))
  end
end

-- LaTeX blocks ----------------------------------------------------------------

local function raw(s) return pandoc.RawBlock('latex', s) end

--- Data macros read by unibs-covers.tex / unibs-style.tex (from DATA.yaml).
function M.data_block(meta)
  local defs = {
    unibsResDir = M.texpath(path.join { M.root, 'res' }),
    unibsStudentName = M.latex(M.get(meta, 'student', 'name')),
    unibsScholarshipType = M.latex(M.get(meta, 'scholarship', 'type') or 'Borsa di ricerca'),
    unibsScholarshipTitle = M.latex(M.get(meta, 'scholarship', 'title')),
    unibsAcademicYear = M.latex(meta['academic-year']),
    unibsDepartmentName = M.latex(M.get(meta, 'department', 'name')),
    unibsCompanyName = M.latex(M.get(meta, 'company', 'name')),
  }
  local names = {}
  for k in pairs(defs) do names[#names + 1] = k end
  table.sort(names)
  local out = { '% --- data from DATA.yaml (generated by the Lua filter) ---' }
  for _, k in ipairs(names) do
    out[#out + 1] = string.format('\\gdef\\%s{%s}', k, defs[k])
  end
  return raw(table.concat(out, '\n'))
end

--- Sets `author` (PDF metadata) to the student's name.
function M.set_author(meta)
  local name = M.get(meta, 'student', 'name')
  if name and not meta.author then meta.author = name end
end

local function link_latex(text, target)
  return inlines_to_latex(pandoc.Inlines { pandoc.Link(text, target) })
end

local function cmd(name, arg) return string.format('\\%s{%s}', name, arg) end

--- Company logo (DATA.yaml company.logo, relative to the project root) as a
--- path LaTeX can include. SVG logos are used through the PDF next to them,
--- created with rsvg-convert when missing. nil (with a warning) on failure.
local function company_logo(meta)
  local logo = M.str(M.get(meta, 'company', 'logo'))
  if logo == '' then return nil end
  local p = path.is_absolute(logo) and logo or path.join { M.root, logo }
  if not exists(p) then
    warn('logo aziendale non trovato: ' .. logo .. ' (company.logo in DATA.yaml)')
    return nil
  end
  local stem, ext = path.split_extension(p)
  if ext:lower() == '.svg' then
    local pdf = stem .. '.pdf'
    if not exists(pdf) then
      local ok = pcall(pandoc.pipe, 'rsvg-convert', { '-f', 'pdf', '-o', pdf, p }, '')
      if not ok then
        warn('impossibile convertire ' .. logo .. ' in PDF (serve rsvg-convert, '
          .. 'vedi README): logo omesso')
        return nil
      end
    end
    p = pdf
  end
  return M.texpath(p)
end

--- Signature of one person: name / role, contacts, department / institution.
--- `institution` is a list of already-rendered \unibsInfo* lines.
local function signature(p, department, institution)
  local out = { cmd('unibsInfoName', M.latex(p.name)) }
  if M.str(p.role) ~= '' then out[#out + 1] = cmd('unibsInfoText', M.latex(p.role)) end
  local email = M.str(p.email)
  if email ~= '' then
    out[#out + 1] = '\\unibsInfoGap'
    out[#out + 1] = cmd('unibsInfoText', link_latex(email, 'mailto:' .. email))
  end
  local dept = M.str(department) ~= '' and cmd('unibsInfoMuted', M.latex(department)) or nil
  if dept or #institution > 0 then
    out[#out + 1] = '\\unibsInfoGap'
    out[#out + 1] = dept
    for _, line in ipairs(institution) do out[#out + 1] = line end
  end
  return table.concat(out, '\n')
end

--- People of one column: label + one or more signatures.
local function people(label, signatures)
  if #signatures == 0 then return '' end
  return cmd('unibsInfoLabel', label) .. '\n' .. table.concat(signatures, '\n\\unibsInfoNext\n')
end

--- Personal-info block: UNIBS column (student, supervisors) and company
--- column (tutor, or the company itself when there is no tutor), each headed
--- by its logo.
function M.info_block(meta)
  local g = function(...) return M.get(meta, ...) end
  local function has(v) return v ~= nil and M.str(v) ~= '' end

  -- Left column: people affiliated with UNIBS.
  local unibs = { cmd('unibsInfoText', M.latex(g('department', 'university')
    or 'Università degli Studi di Brescia')) }
  local default_dept = g('department', 'name')
  local left = {}
  local student = g('student')
  if student and has(student.name) then
    left[#left + 1] = people('Studente',
      { signature(student, student.department or default_dept, unibs) })
  end
  local sups = g('supervisors')
  if sups and utils.type(sups) ~= 'List' then sups = pandoc.List { sups } end
  local sigs = {}
  for _, s in ipairs(sups or {}) do
    if has(s.name) then sigs[#sigs + 1] = signature(s, s.department or default_dept, unibs) end
  end
  if #sigs > 0 then
    left[#left + 1] = people(#sigs > 1 and 'Supervisori' or 'Supervisore', sigs)
  end

  -- Right column: the affiliated company.
  local right, mark = {}, ''
  local company = g('company')
  if company and has(company.name) then
    local url = M.str(company.url)
    local company_lines = { cmd('unibsInfoText', M.latex(company.name)) }
    if url ~= '' then
      company_lines[#company_lines + 1] = cmd('unibsInfoText',
        link_latex(url:gsub('^https?://', ''):gsub('/$', ''), url))
    end
    local tutor = company.tutor
    if tutor and has(tutor.name) then
      right[#right + 1] = people('Tutor aziendale',
        { signature(tutor, tutor.department, company_lines) })
    else
      right[#right + 1] = people('Azienda affiliata', {
        cmd('unibsInfoName', M.latex(company.name))
          .. (url ~= '' and ('\n\\unibsInfoGap\n' .. company_lines[2]) or '') })
    end
    local logo = company_logo(meta)
    mark = logo and cmd('unibsInfoPartnerLogo', logo)
      or cmd('unibsInfoPartnerName', M.latex(company.name))
  end

  return raw(table.concat({
    '\\begin{unibsinfo}',
    string.format('\\unibsInfoLogos{\\unibsInfoUnibsLogo}{%s}', mark),
    string.format('\\unibsInfoColumns{%%\n%s}{%%\n%s}',
      table.concat(left, '\n\\unibsInfoNext\n'), table.concat(right, '\n\\unibsInfoNext\n')),
    '\\end{unibsinfo}',
  }, '\n'))
end

--- Weekly cover. `fallback_date` (ISO) is used when the front matter has none.
function M.weekly_cover(meta, fallback_date)
  local title = meta.title
  if title == nil or M.str(title) == '' then
    warn('report senza `title` nel front matter')
    title = pandoc.Inlines('«Titolo del report»')
  end
  local class = M.title_class(title, { 70, 120, 200 })
  local date = meta.date or fallback_date
  if date == nil then warn('report senza `date` nel front matter') end
  return raw(string.format('\\unibsWeeklyCover[%d]{%s}{%s}{%s}', class,
    M.latex(title), M.latex(M.date_it(date)), M.latex(meta.period)))
end

--- Compendium cover (fields from cover.md).
function M.compendium_cover(meta)
  local title = meta.title or pandoc.Inlines('Report settimanali')
  local class = M.title_class(title, { 40, 80, 130 })
  return raw(string.format('\\unibsCompendiumCover[%d]{%s}{%s}{%s}', class,
    M.latex(title), M.latex(meta.period), M.latex(M.date_it(meta.date))))
end

-- Body styling (applied to every document) -----------------------------------

M.style = {
  -- Code blocks in a branded box (highlighted or not).
  CodeBlock = function(cb)
    return { raw('\\begin{unibscode}'), cb, raw('\\end{unibscode}') }
  end,
  -- Table header cells: bold, Blu notte.
  Table = function(tbl)
    for _, row in ipairs(tbl.head.rows) do
      for _, cell in ipairs(row.cells) do
        local first = cell.contents[1]
        if first and (first.t == 'Plain' or first.t == 'Para') then
          first.content:insert(1, pandoc.RawInline('latex', '\\unibsTableHead '))
        end
      end
    end
    return tbl
  end,
}

return M
